test_that("mkdparse(rdebug = TRUE) prints the debug grammar safely", {
  # print_rdebug_grammar() used a `char ver[30]` buffer for d_version(),
  # which writes "<major>.<minor>.<40-hex git id>" (~46 chars), overflowing
  # the stack; print_term_escaped() also leaked the double-escaped string.
  # The real check is running this under valgrind/ASan (issue #40).
  g <- tempfile(fileext = ".g")
  on.exit(unlink(g), add = TRUE)
  writeLines(
    c(
      "S: A B* C;",
      "A: 'a\\'q' $term 1;",
      "B: \"[b\\\"]+\" | 'x'/i;",
      "C: \"c[0-9]*\";"
    ),
    g
  )
  out <- capture.output(mkdparse(g, tempdir(), rdebug = TRUE))
  expect_true(any(grepl(
    "Generated by Make DParser Version [0-9]+\\.[0-9]+",
    out
  )))
  ver <- regmatches(out, regexpr("Version [^ ]+", out))
  expect_true(length(ver) == 1 && nchar(ver) > nchar("Version ") + 3)
  expect_true(any(grepl("a", out, fixed = TRUE)))
})
